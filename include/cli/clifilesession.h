#ifndef CLI_CLIFILESESSION_H
#define CLI_CLIFILESESSION_H

#include <string>
#include <iostream>
#include "cli.h" // CliSession

namespace cli
{

class CliFileSession : public CliSession
{
public:
    /// 流的有效性由**调用方**保证。本 fork 不在此校验：原先的两个
    /// `throw std::invalid_argument` 在 /EHs-c- / -fno-exceptions 的消费方是解析期
    /// 硬错误，而"降级成什么都不做"会让一个坏输入流静默跑成空会话。
    /// 调用方应自己 `if (!in.good())` 之后再构造。
    explicit CliFileSession(Cli& _cli, std::istream& _in=std::cin, std::ostream& _out=std::cout) :
        CliSession(_cli, _out, 1),
        exit(false),
        in(_in)
    {
        ExitAction(
            [this](std::ostream&) noexcept
            {
                exit = true;
            }
        );
    }
    void Start()
    {
        Enter();

        while(!exit)
        {
            Prompt();
            std::string line;
            if (!in.good())
                Exit();
            std::getline(in, line);
            if (in.eof())
                Exit();
            else
                Feed(line);
        }
    }

private:
    bool exit;
    std::istream& in;
};

} // namespace cli

#endif // CLI_CLIFILESESSION_H

